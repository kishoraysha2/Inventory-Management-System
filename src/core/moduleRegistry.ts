// --- HELPER FUNCTIONS ---

export function getModule(id: string): ModuleDefinition | undefined {
  return MODULE_REGISTRY.find(m => m.id === id);
}

export function getModules(): readonly ModuleDefinition[] {
  return MODULE_REGISTRY;
}

export function getVisibleModules(): ModuleDefinition[] {
  return MODULE_REGISTRY.filter(m => m.visibleInNavigation)
    .sort((a, b) => (a.navigationOrder ?? 999) - (b.navigationOrder ?? 999));
}

export function getBackupModules(): ModuleDefinition[] {
  return MODULE_REGISTRY.filter(m => m.supportsBackup);
}

export function getRestoreModules(): ModuleDefinition[] {
  return MODULE_REGISTRY.filter(m => m.supportsRestore);
}

export function getModuleDependencies(id: string): readonly string[] {
  const mod = getModule(id);
  return mod ? mod.dependencies : [];
}

export function getPermissionModules(): ModuleDefinition[] {
  return MODULE_REGISTRY.filter(m => m.permissions !== undefined);
}

export function getDashboardModules(): ModuleDefinition[] {
  return MODULE_REGISTRY.filter(m => m.supportsDashboard);
}
