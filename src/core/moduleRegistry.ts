export interface ModuleDefinition {
  readonly id: string;
  readonly displayName: string;
  readonly icon: React.ComponentType<{ className?: string }>;
  readonly routeKey?: string; // Key used for activeTab / navigation routes
  readonly collectionNames: readonly string[]; // Firestore collection(s) used by the module
  readonly isSingleton?: boolean;
  readonly singletonDocId?: string; // If singleton, e.g. 'config', 'bootstrap'
  readonly backupPath?: string; // Path inside backup zip, e.g. 'security/users.json'
  readonly category: 'Configuration' | 'Security' | 'Master Data' | 'Transactions' | 'Accounting' | 'System' | 'Core';
  readonly permissions?: {
    readonly view?: string; // e.g. 'viewExpenses', 'viewUsers'
    readonly manage?: string; // e.g. 'manageSettings', 'createCustomer'
  };
  readonly dependencies: readonly string[]; // Dependent module IDs
  readonly supportsBackup: boolean;
  readonly supportsRestore: boolean;
  readonly supportsDashboard: boolean;
  readonly supportsSearch: boolean;
  readonly supportsReports: boolean;
  readonly visibleInNavigation: boolean;
  readonly navigationOrder?: number;
}

